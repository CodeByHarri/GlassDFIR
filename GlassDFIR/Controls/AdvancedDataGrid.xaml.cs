        private void MainGrid_LoadingRow(object sender, DataGridRowEventArgs e)
        {
            var row = e.Row;
            var item = row.Item;
            row.ClearValue(Control.BackgroundProperty); // Reset to allow RowStyle to work

            foreach (var rule in FormattingRules)
            {
                string cellValue = "";
                if (item is DataRowView drv)
                {
                    var table = drv.Row.Table;
                    if (table.Columns.Contains(rule.PropertyName))
                    {
                        cellValue = drv[rule.PropertyName]?.ToString() ?? "";
                    }
                }
                else
                {
                    var prop = item.GetType().GetProperty(rule.PropertyName);
                    cellValue = prop?.GetValue(item)?.ToString() ?? "";
                }

                if (cellValue.Contains(rule.Value, StringComparison.OrdinalIgnoreCase))
                {
                    try
                    {
                        var color = (System.Windows.Media.Color)System.Windows.Media.ColorConverter.ConvertFromString(rule.ColorHex);
                        row.Background = new System.Windows.Media.SolidColorBrush(color) { Opacity = 0.6 };
                    }
                    catch { }
                    break;
                }
            }
        }

