            }
        }

        private T? FindVisualChild<T>(DependencyObject obj) where T : DependencyObject
        {
            for (int i = 0; i < VisualTreeHelper.GetChildrenCount(obj); i++)
            {
                var child = VisualTreeHelper.GetChild(obj, i);
                if (child is T t) return t;
                var childOfChild = FindVisualChild<T>(child);
                if (childOfChild != null) return childOfChild;
            }
            return null;
        }

        private T? FindVisualParent<T>(DependencyObject? child) where T : DependencyObject
        {
            while (child != null)
            {
                if (child is T parent) return parent;
                child = VisualTreeHelper.GetParent(child);
            }
            return null;
        }

        private void SelectAll_Checked(object sender, RoutedEventArgs e) => SetAllDistinct(true);
        private void SelectAll_Unchecked(object sender, RoutedEventArgs e) => SetAllDistinct(false);

        private void SetAllDistinct(bool isChecked)
        {
            if (_isUpdatingSelectAll) return;
            
            _isUpdatingSelectAll = true;
            try
            {
                foreach (var item in _currentDistinctItems) item.IsChecked = isChecked;
                UpdateDistinctFilter();
            }
            finally
            {
                _isUpdatingSelectAll = false;
            }
        }

        private void FilterCheck_Changed(object sender, RoutedEventArgs e)
        {
            if (_isUpdatingSelectAll) return;
            
            _isUpdatingSelectAll = true;
            try
            {
                // Update Select All state based on whether ANY are unchecked
                bool allChecked = _currentDistinctItems.All(i => i.IsChecked);
                if (SelectAllCheckBox.IsChecked != allChecked)
                {
                    SelectAllCheckBox.IsChecked = allChecked;
                }
                UpdateDistinctFilter();
            }
            finally
            {
                _isUpdatingSelectAll = false;
            }
        }

        private void UpdateDistinctFilter()
        {
            if (string.IsNullOrEmpty(_currentFilterProperty)) return;

            // Optimization: If everything is checked, we don't need a filter for this column
            bool allChecked = _currentDistinctItems.All(i => i.IsChecked);
            
            if (allChecked)
            {
                if (_distinctFilters.ContainsKey(_currentFilterProperty))
                    _distinctFilters.Remove(_currentFilterProperty);
            }
            else
            {
                var checkedItems = _currentDistinctItems.Where(i => i.IsChecked).Select(i => i.Value).ToHashSet();
                _distinctFilters[_currentFilterProperty] = checkedItems;
            }

            _view?.Refresh();
            UpdateResultCount();
        }

