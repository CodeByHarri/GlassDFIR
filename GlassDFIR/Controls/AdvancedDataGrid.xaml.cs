        public void ExportToCSV()
        {
            if (_view == null) return;

            var sfd = new Microsoft.Win32.SaveFileDialog
            {
                Filter = "CSV Files (*.csv)|*.csv",
                FileName = $"{PersistenceKey}_Export_{DateTime.Now:yyyyMMdd_HHmm}.csv"
            };

            if (sfd.ShowDialog() == true)
            {
                try
                {
                    using (var writer = new StreamWriter(sfd.FileName))
                    {
                        var columns = MainGrid.Columns.OfType<DataGridBoundColumn>()
                            .Where(c => c.Visibility == Visibility.Visible)
                            .OrderBy(c => c.DisplayIndex)
                            .ToList();

                        // Headers
                        writer.WriteLine(string.Join(",", columns.Select(c => $"\"{c.Header}\"")));

                        // Data
                        foreach (var item in _view)
                        {
                            var values = new List<string>();
                            foreach (var col in columns)
                            {
                               var binding = col.Binding as Binding;
                               if (binding != null && binding.Path != null)
                               {
                                    string val = "";
                                    if (item is DataRowView drv) val = drv[binding.Path.Path]?.ToString() ?? "";
                                    else val = item.GetType().GetProperty(binding.Path.Path)?.GetValue(item)?.ToString() ?? "";
                                    values.Add($"\"{val.Replace("\"", "\"\"")}\"");
                               }
                            }
                            writer.WriteLine(string.Join(",", values));
                        }
                    }
                    MessageBox.Show("Export complete!", "GlassDFIR");
                }
                catch (Exception ex)
                {
                    MessageBox.Show($"Export failed: {ex.Message}", "Error");
                }
            }
        }
