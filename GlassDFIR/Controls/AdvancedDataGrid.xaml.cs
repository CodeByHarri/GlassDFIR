        private void AddFormatting_Click(object sender, RoutedEventArgs e)
        {
            if (MainGrid.CurrentItem == null || MainGrid.CurrentColumn == null) return;

            var item = MainGrid.CurrentItem;
            var col = MainGrid.CurrentColumn;

            if (col is DataGridBoundColumn boundCol && boundCol.Binding is Binding binding)
            {
                var propertyName = binding.Path?.Path;
                if (propertyName == null) return;

                string cellValue = "";

                if (item is DataRowView drv)
                {
                    cellValue = drv[propertyName]?.ToString() ?? "";
                }
                else
                {
                    cellValue = item.GetType().GetProperty(propertyName)?.GetValue(item)?.ToString() ?? "";
                }

                if (!string.IsNullOrEmpty(cellValue))
                {
                    string colorHex = "#f7768e"; // Default
            if (sender is MenuItem mi)
            {
                // Prefer CommandParameter, fallback to Tag
                if (mi.CommandParameter != null)
                {
                    colorHex = mi.CommandParameter.ToString() ?? colorHex;
                }
                else if (mi.Tag != null)
                {
                    colorHex = mi.Tag.ToString() ?? colorHex;
                }
            }

                    var rule = new FormattingRule { PropertyName = propertyName ?? "", Value = cellValue, ColorHex = colorHex };
                    FormattingRules.Add(rule);
                    
                    // Force refresh grid styles
                    RefreshGridStyles();
                }
            }
        }

