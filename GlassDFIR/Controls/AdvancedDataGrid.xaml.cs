        private bool ExecuteFilter(object obj)
        {
            // 1. Check Global Filter
            bool matchesGlobal = true;
            if (!string.IsNullOrWhiteSpace(GlobalFilterText))
            {
                matchesGlobal = false;
                
                if (obj is DataRowView drv)
                {
                   // DataRowView is fast enough usually, but can be optimized if needed
                    foreach (var item in drv.Row.ItemArray)
                    {
                        if (item != null && (item.ToString() ?? "").Contains(GlobalFilterText, StringComparison.OrdinalIgnoreCase))
                        {
                            matchesGlobal = true;
                            break;
                        }
                    }
                }
                else
                {
                    // Optimization: Cache properties to avoid GetProperties() on every row
                    var type = obj.GetType();
                    if (!_propertyCache.TryGetValue(type, out var props))
                    {
                        props = type.GetProperties().Where(p => p.CanRead).ToArray();
                        _propertyCache[type] = props;
                    }

                    foreach (var prop in props)
                    {
                        var val = prop.GetValue(obj)?.ToString();
                        if (val != null && val.Contains(GlobalFilterText, StringComparison.OrdinalIgnoreCase))
                        {
                            matchesGlobal = true;
                            break;
                        }
                    }
                }
            }

            if (!matchesGlobal) return false;

            if (!matchesGlobal) return false;

            // 2. Check Column-Specific Filters (Text search and Distinct values)
            var objType = obj.GetType();
            
            // Text Search Filters
            if (_columnFilters.Count > 0 && !_columnFilters.Values.All(string.IsNullOrWhiteSpace))
            {
                foreach (var filter in _columnFilters)
                {
                    if (string.IsNullOrWhiteSpace(filter.Value)) continue;

                    string cellValue = GetCellValue(obj, filter.Key);
                    if (!cellValue.Contains(filter.Value, StringComparison.OrdinalIgnoreCase))
                        return false;
                }
            }

            // Distinct Value Filters
            if (_distinctFilters.Count > 0)
            {
                foreach (var filter in _distinctFilters)
                {
                    string cellValue = GetCellValue(obj, filter.Key);
                    if (string.IsNullOrEmpty(cellValue)) cellValue = "(Blanks)";
                    
                    if (!filter.Value.Contains(cellValue))
                        return false;
                }
            }

            // 3. Time Range Filter
            if (_activeTimeFilter != null)
            {
                DateTime? rowTime = null;
                
                // Ensure property name is valid
                if (string.IsNullOrEmpty(_activeTimeFilter.PropertyName)) return true;

                if (obj is DataRowView drv)
                {
                     if (drv.Row.Table.Columns.Contains(_activeTimeFilter.PropertyName))
                     {
                         var val = drv[_activeTimeFilter.PropertyName];
                         if (val != DBNull.Value)
                         {
                             if (val is DateTime dt) rowTime = dt;
                             else if (val is string s && DateTime.TryParse(s, out var parsed)) rowTime = parsed;
                         }
                     }
                }
                else
                {
                     // Optimization: Cache PropertyInfo
                     // Check nulls before comparing
                     if (_cachedTimePropertyName != _activeTimeFilter.PropertyName || _cachedTimeProperty == null)
                     {
                         _cachedTimePropertyName = _activeTimeFilter.PropertyName;
                         _cachedTimeProperty = obj.GetType().GetProperty(_activeTimeFilter.PropertyName);
                     }

                     if (_cachedTimeProperty != null)
                     {
                         var val = _cachedTimeProperty.GetValue(obj);
                          if (val != null)
                          {
                              if (val is DateTime dt) rowTime = dt;
                              else if (val is string s)
                              {
                                  // Try rigorous parsing
                                  if (DateTime.TryParse(s, System.Globalization.CultureInfo.InvariantCulture, System.Globalization.DateTimeStyles.None, out var parsed))
                                      rowTime = parsed;
                                  else if (DateTime.TryParse(s, out parsed)) // Fallback to current culture
                                      rowTime = parsed;
                              }
                          }
                     }

                }

                if (rowTime.HasValue)
                {
                    // Check range
                    bool inRange = rowTime.Value >= _activeTimeFilter.Start && rowTime.Value <= _activeTimeFilter.End;
                    if (!inRange) return false;
                }
            }

            return true;
        }






        private TimeRangeEventArgs? _activeTimeFilter; // Can be null
        private System.Reflection.PropertyInfo? _cachedTimeProperty; // Can be null
        private string? _cachedTimePropertyName; // Can be null

        private string GetCellValue(object obj, string propertyName)
        {
            if (obj is DataRowView drv)
            {
                if (drv.Row.Table.Columns.Contains(propertyName))
                    return drv[propertyName]?.ToString() ?? "";
            }
            else
            {
                var prop = obj.GetType().GetProperty(propertyName);
                if (prop != null)
                {
                    return prop.GetValue(obj)?.ToString() ?? "";
                }
                else if (obj is IDictionary<string, object> dict && dict.ContainsKey(propertyName))
                {
                    return dict[propertyName]?.ToString() ?? "";
                }
            }
            return "";
        }

