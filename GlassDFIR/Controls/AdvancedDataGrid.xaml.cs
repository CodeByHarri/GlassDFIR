        private void OpenValueViewer()
        {
            if (MainGrid.CurrentCell == default || !MainGrid.CurrentCell.IsValid) return;

            var cellInfo = MainGrid.CurrentCell;
            var column = cellInfo.Column;
            var item = cellInfo.Item;

            if (column == null || item == null) return;

            try 
            {
                var content = column.GetCellContent(item);
                string text = "";

                if (content is TextBlock tb)
                {
                    text = tb.Text;
                }
                else if (content is ContentPresenter cp && cp.Content != null)
                {
                   text = cp.Content.ToString() ?? "";
                }
                else if (content != null)
                {
                    // Fallback: try to find a TextBlock inside
                    var childTb = FindVisualChild<TextBlock>(content);
                    if (childTb != null) text = childTb.Text;
                    else text = content.ToString() ?? "";
                }

                if (!string.IsNullOrEmpty(text))
                {
                    var viewer = new ValueViewer(text);
                    viewer.Owner = Window.GetWindow(this);
                    viewer.ShowDialog();
                }
            }
            catch (Exception)
            {
                // Fallback for complex virtualization scenarios or detached items
            }
        }

