        private void UpdateColumnFilteredState(string propertyName)
        {
            var column = MainGrid.Columns.FirstOrDefault(c => (c as DataGridBoundColumn)?.Binding is Binding b && b.Path?.Path == propertyName);
            if (column == null) return;

            bool hasTextFilter = _columnFilters.TryGetValue(propertyName, out var text) && !string.IsNullOrWhiteSpace(text);
            bool hasDistinctFilter = _distinctFilters.ContainsKey(propertyName);

            SetIsColumnFiltered(column, hasTextFilter || hasDistinctFilter);
        }

        private void OpenFilterForColumn(DataGridColumn gridColumn)
        {
            if (gridColumn is DataGridBoundColumn boundCol && boundCol.Binding is Binding binding)
            {
                var propertyName = binding.Path?.Path;
                if (string.IsNullOrEmpty(propertyName) || _view == null) return;

                _currentFilterProperty = propertyName;
                
                // Collect distinct values
                var distinctValues = new HashSet<string>();
                var source = _view.SourceCollection.Cast<object>();

                foreach (var item in source)
                {
                    string val = "";
                    if (item is DataRowView drv)
                    {
                        val = drv[propertyName]?.ToString() ?? "(Blanks)";
                    }
                    else
                    {
                        val = item.GetType().GetProperty(propertyName)?.GetValue(item)?.ToString() ?? "(Blanks)";
                    }
                    if (string.IsNullOrEmpty(val)) val = "(Blanks)";
                    distinctValues.Add(val);
                }

                var activeFilters = _distinctFilters.ContainsKey(propertyName) ? _distinctFilters[propertyName] : null;

                _currentDistinctItems = distinctValues.OrderBy(v => v).Select(v => new DistinctValueItem 
                { 
                    Value = v, 
                    IsChecked = activeFilters == null || activeFilters.Contains(v)
                }).ToList();

                DistinctValuesList.ItemsSource = _currentDistinctItems;
                
