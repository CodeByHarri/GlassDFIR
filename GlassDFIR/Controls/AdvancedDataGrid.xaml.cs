        public void SortByColumn(string propertyName, System.ComponentModel.ListSortDirection direction)
        {
            if (_view == null) return;

            var column = MainGrid.Columns.FirstOrDefault(c => 
            {
                if (c is DataGridBoundColumn boundCol && boundCol.Binding is Binding binding)
                {
                    return binding.Path?.Path == propertyName;
                }
                return false;
            });

            using (_view.DeferRefresh())
            {
                _view.SortDescriptions.Clear();
                foreach (var c in MainGrid.Columns)
                {
                    c.SortDirection = null;
                }

                _view.SortDescriptions.Add(new System.ComponentModel.SortDescription(propertyName, direction));
                if (column != null)
                {
                    column.SortDirection = direction;
                }
            }
        }

