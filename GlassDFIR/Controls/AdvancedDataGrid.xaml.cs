        private void MainGrid_Sorting(object sender, DataGridSortingEventArgs e)
        {
            if (_view == null) return;

            e.Handled = true; // We'll handle sorting ourselves
            var column = e.Column;
            var direction = column.SortDirection == System.ComponentModel.ListSortDirection.Ascending ? System.ComponentModel.ListSortDirection.Descending : System.ComponentModel.ListSortDirection.Ascending;

            using (_view.DeferRefresh())
            {
                if ((System.Windows.Input.Keyboard.Modifiers & System.Windows.Input.ModifierKeys.Shift) != System.Windows.Input.ModifierKeys.Shift)
                {
                    _view.SortDescriptions.Clear();
                    foreach (var c in MainGrid.Columns)
                    {
                        if (c != column) c.SortDirection = null;
                    }
                }

                if (column is DataGridBoundColumn boundCol && boundCol.Binding is Binding binding)
                {
                    var propertyName = binding.Path?.Path;
                    if (propertyName == null) return; // Should not happen for bound columns

                    // Remove existing sort for this property if multi-sorting
                    var existing = _view.SortDescriptions.FirstOrDefault(sd => sd.PropertyName == propertyName);
                    if (existing != default) _view.SortDescriptions.Remove(existing);

                    _view.SortDescriptions.Add(new System.ComponentModel.SortDescription(propertyName, direction));
                    column.SortDirection = direction;
                }
            }
        }

        private void MainGrid_AutoGeneratingColumn(object? sender, DataGridAutoGeneratingColumnEventArgs e)
        {
            // Force valid width to ensure scrollbar activation
            // SizeToHeader might still be too small for short headers (like "ID"), so we use a strict minimum.
            e.Column.Width = 200;

            // Set Type Icon in Tag
            string typeIcon = "[abc]"; // Default to string
            var type = e.PropertyType;

            // ... (rest of type sniffing logic) ...


            // Type Sniffing for CSV/Untyped data
            if (type == typeof(string) && MainGrid.ItemsSource != null)
            {
                var firstItem = MainGrid.ItemsSource.Cast<object>().FirstOrDefault();
                if (firstItem != null)
                {
                    string? val = null;
                    if (firstItem is DataRowView drv)
                    {
                        val = drv[e.PropertyName]?.ToString();
                    }
                    else
                    {
                        val = firstItem.GetType().GetProperty(e.PropertyName)?.GetValue(firstItem)?.ToString();
                    }

                    if (!string.IsNullOrEmpty(val))
                    {
                        if (DateTime.TryParse(val, out _))
                        {
                            type = typeof(DateTime);
                            typeIcon = "[🕒]";
                        }
                        else if (long.TryParse(val, out _))
                        {
                            type = typeof(long);
                            typeIcon = "[123]";
                        }
                        else if (double.TryParse(val, out _))
                        {
                            type = typeof(double);
                            typeIcon = "[123]";
                        }
                    }
                }
            }
            else if (type == typeof(int) || type == typeof(long) || type == typeof(double) || type == typeof(decimal))
            {
                typeIcon = "[123]";
            }
            else if (type == typeof(DateTime))
            {
                typeIcon = "[🕒]";
            }
            
            SetColumnTypeIcon(e.Column, typeIcon);

            if (type == typeof(DateTime))
            {
                var column = e.Column as DataGridTextColumn;
                if (column != null && column.Binding is Binding binding && binding.Path != null)
                {
                    column.Binding.StringFormat = "yyyy-MM-dd HH:mm:ss.ffff";
                }
            }



            // Apply Highlighting Style to Text Columns
            if (e.Column is DataGridTextColumn textColumn)
            {
                try 
                {
                    textColumn.ElementStyle = this.FindResource("HighlightedTextBlockStyle") as Style;
                }
                catch (Exception ex)
                {
                    System.Diagnostics.Debug.WriteLine($"Error applying HighlightedTextBlockStyle: {ex.Message}");
                }
            }
        }

        private void RestoreState()
        {
            if (_pendingState == null) return;

            foreach (var col in MainGrid.Columns)
            {
                var saved = _pendingState.Columns.FirstOrDefault(c => c.PropertyName == col.SortMemberPath || c.PropertyName == col.Header.ToString());
                if (saved != null)
                {
                    // Restore width, but enforce minimum 200px to fix "squashed" saves
                    col.Width = Math.Max(saved.Width, 200);
                    col.DisplayIndex = Math.Min(saved.DisplayIndex, MainGrid.Columns.Count - 1);
                    col.Visibility = saved.IsVisible ? Visibility.Visible : Visibility.Collapsed;
                }
            }
            
            // Clear pending state after applying
            _pendingState = null; 
        }

