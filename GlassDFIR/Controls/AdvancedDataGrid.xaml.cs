        private void FilterForValue_Click(object sender, RoutedEventArgs e)
        {
            if (_lastClickedColumn != null && !string.IsNullOrEmpty(_lastClickedValue))
            {
                // Find the TextBox for this column in the FilterRow
                foreach (var item in FilterRow.Items)
                {
