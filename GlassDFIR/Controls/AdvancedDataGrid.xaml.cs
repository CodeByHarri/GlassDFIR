        private IntPtr WndProc(IntPtr hwnd, int msg, IntPtr wParam, IntPtr lParam, ref bool handled)
        {
            const int WM_MOUSEHWHEEL = 0x020E;
            if (msg == WM_MOUSEHWHEEL)
            {
                int delta = (short)((wParam.ToInt64() >> 16) & 0xFFFF);
                if (delta != 0)
                {
                    // Find the ScrollViewer inside the DataGrid
                    var scrollViewer = FindVisualChild<ScrollViewer>(MainGrid);
                    if (scrollViewer != null)
                    {
                        if (delta < 0)
                            scrollViewer.LineRight();
                        else
                            scrollViewer.LineLeft();
                        handled = true;
                    }
                }
            }
            return IntPtr.Zero;
        }

        private async void SaveState() => await InternalSaveStateAsync(PersistenceKey);

        private async Task InternalSaveStateAsync(string? key)
        {
            if (_isLoading || string.IsNullOrEmpty(key)) return;

            var state = new GridSessionState();


            state.FormattingRules = FormattingRules.ToList();

            foreach (var col in MainGrid.Columns)
            {
                if (col is DataGridBoundColumn bc && bc.Binding is Binding b)
                {
                    state.Columns.Add(new ColumnState
                    {
                        PropertyName = b.Path.Path,
                        Width = col.ActualWidth,
                        DisplayIndex = col.DisplayIndex,
                        IsVisible = col.Visibility == Visibility.Visible
                    });
                }
            }

            try
            {
                string dir = Path.Combine(AppDomain.CurrentDomain.BaseDirectory, "Config", "Layouts");
                Directory.CreateDirectory(dir);
                string path = Path.Combine(dir, $"{key}.json");
                string json = JsonSerializer.Serialize(state);
                await File.WriteAllTextAsync(path, json);
            }
            catch { }
        }

        private async void LoadState()
        {
            if (string.IsNullOrEmpty(PersistenceKey)) return;

            _isLoading = true;
            try
            {
                string path = Path.Combine(AppDomain.CurrentDomain.BaseDirectory, "Config", "Layouts", $"{PersistenceKey}.json");
                
                GridSessionState? state = null;
                if (File.Exists(path))
                {
                    try 
                    {
                        string json = await File.ReadAllTextAsync(path);
                        state = JsonSerializer.Deserialize<GridSessionState>(json);
                    } catch { }
                }

                FormattingRules.Clear();
                
                if (state != null && state.FormattingRules != null)
                {
                    foreach (var r in state.FormattingRules) FormattingRules.Add(r);
                    _pendingState = state;
                }
                else if (DefaultRules != null)
                {
                    foreach (var r in DefaultRules) FormattingRules.Add(r);
                }
            }
            finally
            {
                _isLoading = false;
            }
        }

