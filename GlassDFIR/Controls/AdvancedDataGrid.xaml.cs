        private void MainGrid_ContextMenuOpening(object sender, ContextMenuEventArgs e)
        {
            // Reset captured state
            _lastClickedValue = null;
            _lastClickedColumn = null;

            var hitTestResult = VisualTreeHelper.HitTest(MainGrid, Mouse.GetPosition(MainGrid));
            if (hitTestResult != null)
            {
                // If it's a header, swallow the menu (already handled in PreviewMouseRightButtonUp)
                var header = FindVisualParent<DataGridColumnHeader>(hitTestResult.VisualHit);
                if (header != null)
                {
                    e.Handled = true;
                    return;
                }

                // If it's a cell, capture the value and column for the menu
                var cell = FindVisualParent<DataGridCell>(hitTestResult.VisualHit);
                if (cell != null)
                {
                    _lastClickedColumn = cell.Column;
                    var item = cell.DataContext;

                    if (cell.Column is DataGridBoundColumn boundCol && boundCol.Binding is Binding binding)
                    {
                        var propertyName = binding.Path?.Path;
                        if (!string.IsNullOrEmpty(propertyName))
                        {
                            if (item is DataRowView drv) _lastClickedValue = drv[propertyName]?.ToString();
                            else _lastClickedValue = item?.GetType().GetProperty(propertyName)?.GetValue(item)?.ToString();
                        }
                    }
                }
            }
        }

